import assert from 'node:assert/strict';
import {readFile,writeFile} from 'node:fs/promises';
import path from 'node:path';
import {randomUUID} from 'node:crypto';
import {chromium} from 'playwright';
const run=process.argv[2];
assert.match(run||'',/^p0p1-m1-[A-Za-z0-9_-]+$/);
const root=path.resolve('output',run),out=path.resolve('docs/verification/p0p1/M1');
const seed=JSON.parse(await readFile(path.join(root,'seed.json'),'utf8'));
const report=JSON.parse(await readFile(path.join(out,'desktop-partial.json'),'utf8'));
assert.equal(report.run,run);
const browser=await chromium.connectOverCDP('http://127.0.0.1:9254');
try {
 const pages=browser.contexts().flatMap(c=>c.pages());
 const wb=pages.find(p=>p.url().includes('workbench=1')),paper=pages.find(p=>p.url()==='http://tauri.localhost/');
 const invoke=(command,args={})=>wb.evaluate(({command,args})=>window.__TAURI_INTERNALS__.invoke(command,args),{command,args});
 assert.equal(path.resolve((await invoke('get_paper_bridge_status')).connectionFile),path.join(root,'paper-test/paper-agent-bridge.json'));
 const api=(action,input={})=>invoke('paper_execute',{action,input:{...input,...(action.startsWith('get_')?{}:{requestId:randomUUID()})}});
 const state=async()=>(await api('get_state')).state;
 const pass=message=>{report.checks.push(message);console.log('PASS',message)};
 let s=await state();
 if(process.argv[3] !== 'records-only') {
 const second=s.planning.dayItems.find(i=>i.id===seed.second.item.id);
 await api('workbench_move_item',{itemId:second.id,expectedItemRevision:second.revision,date:seed.today,beforeItemId:seed.first.item.id});
 await paper.locator('.sheet-queue-item').first().filter({hasText:'今日第二步'}).waitFor();
 assert.deepEqual(await paper.locator('.sheet-queue-item').evaluateAll(nodes=>nodes.map(n=>n.dataset.planItemId)),[second.id,seed.first.item.id]);
 pass('Named reorder is reflected in the real Paper queue with original object identities');
 s=await state();
 const task=s.tasks.find(t=>t.id===seed.future.task.id),step=s.planning.steps.find(t=>t.id===seed.future.step.id);
 await api('workbench_save_step',{taskId:task.id,stepId:step.id,expectedTaskRevision:task.revision,expectedStepRevision:step.revision,title:task.title,text:step.text,category:task.category,plannedSeconds:step.plannedSeconds,date:seed.today});
 await wb.locator(`[data-row-id="${seed.future.item.id}"]`).getByRole('button',{name:'放回待安排',exact:true}).click();
 const dialog=wb.getByRole('dialog');
 assert.equal(await dialog.getByLabel('将取消的安排').locator('li').count(),1);
 assert.match(await dialog.innerText(),/1 条有效安排会保留/);
 await dialog.getByRole('button',{name:'确认取消 1 条安排',exact:true}).click();
 await wb.getByRole('status').filter({hasText:'仍有 1 条有效安排'}).waitFor();
 s=await state();
 assert.equal(s.planning.dayItems.find(i=>i.id===seed.future.item.id).removedAt,null);
 assert(s.sessions.every(session=>session.status==='finished'));
 pass('Unplan preview retains the executed source arrangement and reports the remaining arrangement truthfully');
 await writeFile(path.join(out,'desktop-partial.json'),JSON.stringify(report,null,2));
 }
 await wb.getByRole('tab',{name:'每日记录',exact:true}).click();
 await wb.getByRole('article',{name:`${seed.today}每日记录`}).waitFor();
 assert.match(await wb.locator('.wk-journal').innerText(),/提前执行未来步骤/);
 await wb.getByRole('button',{name:'Markdown 原文',exact:true}).click();
 await wb.getByLabel('Markdown 原始内容').filter({hasText:'提前执行未来步骤'}).waitFor();
 await wb.screenshot({path:path.join(out,'markdown.png')});
 const docs=await invoke('workbench_read_documents',{date:seed.today});
 const personal=docs.documents.find(d=>d.kind==='personal');
 assert(path.resolve(personal.path).startsWith(path.join(root,'paper-test')+path.sep));
 const original=await readFile(personal.path,'utf8');
 const edited=original+'\n隔离验收：外部个人笔记应保留。\n';
 await writeFile(personal.path,edited);
 await wb.locator('.wk-document-tools select').selectOption('personal');
 await wb.getByRole('button',{name:'重新读取 Markdown',exact:true}).click();
 await wb.getByLabel('Markdown 原始内容').filter({hasText:'外部个人笔记应保留'}).waitFor();
 s=await state();
 const firstStep=s.planning.steps.find(t=>t.id===seed.first.step.id);
 await api('set_step_completed',{taskId:firstStep.taskId,stepId:firstStep.id,expectedTaskRevision:s.tasks.find(t=>t.id===firstStep.taskId).revision,expectedStepRevision:firstStep.revision,completed:true});
 assert.equal(await readFile(personal.path,'utf8'),edited);
 pass('Native daily record and raw Markdown show execution; an external personal-note edit survives a subsequent task export');
 await writeFile(path.join(out,'desktop-partial.json'),JSON.stringify(report,null,2));
} finally {await browser.close();}
