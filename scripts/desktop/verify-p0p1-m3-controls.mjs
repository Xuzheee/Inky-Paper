import assert from 'node:assert/strict';
import {writeFile,mkdir} from 'node:fs/promises';
import path from 'node:path';
import {randomUUID} from 'node:crypto';
import {chromium} from 'playwright';
const run=process.argv[2];assert.match(run||'',/^p0p1-m3-[\w-]+$/);
const b=await chromium.connectOverCDP('http://127.0.0.1:9254');
const wb=b.contexts().flatMap(c=>c.pages()).find(p=>p.url().includes('workbench=1'));assert(wb);
wb.setDefaultTimeout(15000);
const invoke=(command,args={})=>wb.evaluate(({command,args})=>window.__TAURI_INTERNALS__.invoke(command,args),{command,args});
const api=(action,input={})=>invoke('paper_execute',{action,input:{...input,...(!action.startsWith('get_')?{requestId:randomUUID()}:{})}});
const get=async()=>(await api('get_state')).state;
const out='docs/verification/p0p1/M3';await mkdir(out,{recursive:true});
const report={run,checks:[],modelCalls:0};
try{
 assert.equal(path.resolve((await invoke('get_paper_bridge_status')).connectionFile),path.resolve('output',run,'paper-test/paper-agent-bridge.json'));
 const before=await get(),history=await invoke('workbench_history',{sessionId:null});
 await wb.getByLabel('发送给 Coach',{exact:true}).fill('M3 保留这段未发送的草稿');
 await wb.getByRole('button',{name:'收起 Coach',exact:true}).click();
 assert.equal(await wb.getByLabel('发送给 Coach',{exact:true}).isVisible(),false);
 await wb.getByRole('button',{name:'展开 Coach',exact:true}).click();
 assert.equal(await wb.getByLabel('发送给 Coach',{exact:true}).inputValue(),'M3 保留这段未发送的草稿');
 await wb.reload();
 assert.equal(await wb.getByLabel('发送给 Coach',{exact:true}).inputValue(),'M3 保留这段未发送的草稿');
 await wb.getByRole('button',{name:'连接检查',exact:true}).click();
 await wb.locator('.wk-diagnostics li').first().waitFor();
 assert.equal(await wb.locator('.wk-diagnostics li').count(),4);
 const diag=await invoke('workbench_diagnostics');
 assert.equal(diag.checks.find(c=>c.stage==='model').code,'unknown');
 await wb.getByRole('button',{name:'重新检查',exact:true}).click();
 assert.deepEqual(await invoke('workbench_history',{sessionId:null}),history);
 assert.deepEqual((await get()).sessions,before.sessions);
 report.diagnostics=diag;
 report.checks.push('Collapsed and reloaded composer preserves its scoped draft; read-only four-stage diagnostics creates no conversation or clock');
 await wb.screenshot({path:`${out}/diagnostics.png`});
 await wb.getByRole('button',{name:'连接检查',exact:true}).click();
 const today=await wb.evaluate(()=>new Date().toLocaleDateString('en-CA'));
 const tomorrow=await wb.evaluate(()=>{const d=new Date();d.setDate(d.getDate()+1);return d.toLocaleDateString('en-CA')});
 for(const [i,startMinute,durationMinutes] of [[1,600,20],[2,630,30]]) if(!(await get()).tasks.some(t=>t.title===`M3 批量 ${i}`)) await api('workbench_save_step',{taskId:randomUUID(),stepId:randomUUID(),title:`M3 批量 ${i}`,text:`M3 批量步骤 ${i}`,category:'work',plannedSeconds:900,date:today,startMinute,durationMinutes});
 await wb.getByRole('button',{name:'刷新',exact:true}).click();
 const seeded=await get(),items=seeded.planning.dayItems.filter(x=>seeded.tasks.find(t=>t.id===x.taskId)?.title.startsWith('M3 批量'));
 assert.equal(items.length,2);
 await wb.getByRole('button',{name:'批量改期',exact:true}).click();
 const dialog=wb.getByRole('dialog',{name:'批量改期'});
 await dialog.getByLabel('批量改期目标日期').fill(tomorrow);
 for(let i=1;i<=2;i++)await dialog.getByRole('checkbox',{name:`选择安排 M3 批量步骤 ${i} · ${today}`,exact:true}).check();
 await dialog.getByRole('button',{name:'生成改期预览',exact:true}).click();
 await dialog.getByRole('checkbox',{name:'选择调整组 1',exact:true}).waitFor();
 assert.deepEqual((await get()).planning.dayItems,seeded.planning.dayItems);
 await dialog.getByRole('checkbox',{name:'选择调整组 1',exact:true}).check();
 await wb.screenshot({path:`${out}/bulk-preview.png`});
 await dialog.getByRole('button',{name:'采用所选 1 组调整',exact:true}).click();
 await dialog.getByText('所选调整已采用。原目标和已有执行记录保留。',{exact:true}).waitFor();
 const after=await get();
 for(const old of items){const item=after.planning.dayItems.find(x=>x.id===old.id);assert.equal(item.date,tomorrow);assert.equal(item.startMinute,old.startMinute);assert.equal(item.durationMinutes,old.durationMinutes)}
 assert.deepEqual(after.sessions,seeded.sessions);assert.equal(after.tasks.length,seeded.tasks.length);
 report.checks.push('Native batch reschedule previews without writing, adopts one dependent group atomically, preserves original times/reservations/session snapshots and task count');
 await dialog.getByRole('button',{name:'关闭批量改期',exact:true}).click();
 report.passed=true;
}catch(e){report.failure=String(e);await wb.screenshot({path:`${out}/controls-failure.png`});throw e}
finally{await writeFile(`${out}/controls.json`,JSON.stringify(report,null,2));await b.close()}
