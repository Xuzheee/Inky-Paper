import assert from 'node:assert/strict';
import {writeFile,mkdir} from 'node:fs/promises';
import path from 'node:path';
import {chromium} from 'playwright';
const run=process.argv[2]||'workbench-acceptance-2';
if(!/^[A-Za-z0-9_-]+$/.test(run))throw Error('Invalid directory');
const out=path.resolve('output/playwright',run);await mkdir(out,{recursive:true});
const browser=await chromium.connectOverCDP('http://127.0.0.1:9254');
const p=browser.contexts()[0].pages().find(p=>p.url().includes('workbench'));p.setDefaultTimeout(12000);
const api=(action,input={})=>p.evaluate(({action,input})=>window.__TAURI_INTERNALS__.invoke('paper_execute',{action,input}),{action,input});
const state=async()=>(await api('get_state')).state;
const bridge=await p.evaluate(()=>window.__TAURI_INTERNALS__.invoke('get_paper_bridge_status'));
assert.equal(path.resolve(bridge.connectionFile),path.resolve(`output/${run}/paper-test/paper-agent-bridge.json`));
const checks=[];const pass=s=>{checks.push(s);console.log('PASS',s);};
try {
  await p.getByRole('button',{name:'已加入计划',exact:true}).waitFor();
  const before=await p.evaluate(()=>window.__TAURI_INTERNALS__.invoke('workbench_history',{sessionId:null}));
  assert(before.sessions.length>0);pass('Application restart restores local conversation');
  await p.getByLabel('发送给 Coach',{exact:true}).fill('请接着上次对话，只回答上次提出的候选动作名称，不调用工具、不修改任务。');
  await p.getByRole('button',{name:'发送',exact:true}).click();
  console.log('Waiting for persisted ACP session/load and a real follow-up…');
  await p.getByRole('button',{name:'停止回复',exact:true}).waitFor({state:'hidden',timeout:420000});
  assert.match(await p.locator('.wk-message.assistant').last().innerText(),/检查对话恢复/);
  const history=await p.evaluate(id=>window.__TAURI_INTERNALS__.invoke('workbench_history',{sessionId:id}),before.sessions[0].id);
  assert.equal(history.messages.length,4);assert.equal(history.sessions[0].id,before.sessions[0].id);pass('ACP resumes the same session without duplicating replayed messages');
  await p.getByLabel('发送给 Coach',{exact:true}).fill('请详细解释如何把一项模糊任务拆成能够开始的步骤。只讨论，不调用工具。');
  await p.getByRole('button',{name:'发送',exact:true}).click();
  await p.getByRole('button',{name:'停止回复',exact:true}).click();
  await p.getByRole('button',{name:'停止回复',exact:true}).waitFor({state:'hidden',timeout:15000});
  pass('Stop cancels the active response within 15 seconds');
  await p.getByRole('tab',{name:'日程',exact:true}).click();
  const date=new Date();date.setDate(date.getDate()+1);const d=`${date.getFullYear()}-${String(date.getMonth()+1).padStart(2,'0')}-${String(date.getDate()).padStart(2,'0')}`;
  await p.getByRole('button',{name:`${d} 10:00添加日程`,exact:true}).click();
  assert.equal(await p.getByRole('dialog').getByLabel('开始时间',{exact:true}).inputValue(),'10:00');
  await p.getByRole('dialog').getByLabel('任务名称',{exact:true}).fill('核对交付清单');
  await p.getByRole('dialog').getByRole('button',{name:'保存计划',exact:true}).click();
  await p.getByRole('dialog').waitFor({state:'hidden'});pass('Clicking a calendar hour pre-fills the corresponding time');
  await p.getByRole('tab',{name:'任务',exact:true}).click();
  await p.getByRole('button',{name:'修改 核对交付清单',exact:true}).click();
  await p.getByRole('dialog').getByLabel('任务名称',{exact:true}).fill('核对最终清单');
  let s=await state();const t=s.tasks.find(t=>t.title==='核对交付清单');
  await api('update_task',{requestId:crypto.randomUUID(),taskId:t.id,expectedRevision:t.revision,patch:{title:'另一窗口更新的标题'}});
  await p.getByRole('dialog').getByText('最新任务：另一窗口更新的标题',{exact:true}).waitFor();
  assert(await p.getByRole('dialog').getByRole('button',{name:'保存计划',exact:true}).isDisabled());
  assert.equal(await p.getByRole('dialog').getByLabel('任务名称',{exact:true}).inputValue(),'核对最终清单');
  await p.getByRole('dialog').getByRole('checkbox',{name:'已核对，使用当前草稿保存'}).click();
  await p.getByRole('dialog').getByRole('button',{name:'保存计划',exact:true}).click();
  await p.getByRole('dialog').waitFor({state:'hidden'});assert((await state()).tasks.some(t=>t.title==='核对最终清单'));pass('Concurrent task edits preserve the draft and require a visible conflict review');
  assert.equal((await state()).sessions.length,0);
  await p.screenshot({path:path.join(out,'resume-final.png')});
  await writeFile(path.join(out,'resume-verification.json'),JSON.stringify({checks},null,2));
}finally {await writeFile(path.join(out,'resume-partial-checks.json'),JSON.stringify({checks},null,2));await browser.close();}
